#!/usr/bin/env python3
"""
Смета — одна функция на весь пакет.

Зачем отдельный модуль. Если смету пишет каждый вызывающий сам, каждый пишет
своё: один называет цену за штуку, другой — количество, третий молчит. Цена за
штуку не смета: складывать её на глаз человек не обязан.

Что обязана сказать смета — четыре ответа вместе:

  1. **сколько обращений** — именно количество, а не цена за штуку;
  2. **к какому платному источнику** — Search API, Wordstat;
  3. **по какому проекту и домену**;
  4. **что уже накоплено** и потому не будет пересниматься.

Пятое, не обязательное, но всегда полезное: **чем считано** количество
(`из_чего`). Число без разбора — то же самое мнение, что и позиция без истории.

Деньги называются или объявляются неизвестными. «867 обращений» человеку ни о
чём не говорит. Ставка берётся из тарифов (`rates.json` рядом с пакетом,
перекрывается файлом `$YASEO_RATES` и переменными окружения), и пока она не
задана, смета печатает это прямо: «Стоимость в рублях: неизвестна — ставка не
задана». Подставлять ставку, которой не вернул источник, нельзя.
Потолок называется всегда — в том числе словами «не задан».

Бесплатное тоже получает смету. «Ничего не потрачено» — такая же смета, как и
платная, и печатается так же явно.

Пользование

    from yaseo import estimate

    e = estimate.estimate(
        "search-api", 867,
        project="Мой сайт", domain="example.ru",
        из_чего="289 фраз × 3 снимка",
        накоплено="замеров по example.ru ещё нет — пересниматься нечему",
    )
    estimate.text(e)      # многострочно
    estimate.one_line(e)  # одной строкой, для подтверждения перед тратой
    estimate.html(e)      # тот же текст списком, для страницы

Экранировать html() снаружи не нужно и нельзя: он экранирует сам.
"""
from __future__ import annotations

import json
import os
import sys
from html import escape
from importlib import resources
from pathlib import Path

#: Ставки платных источников в рублях за одно обращение.
#:
#: Старшинство: переменная окружения → файл `$YASEO_RATES` → `rates.json`
#: внутри пакета → не задана. Окружение сильнее файла тем же правилом, что у
#: потолка в `tracker.max_calls`.
def rates_path() -> Path:
    """Файл тарифов: `$YASEO_RATES` или встроенный `rates.json`."""
    raw = os.environ.get("YASEO_RATES", "").strip()
    if raw:
        return Path(raw).expanduser()
    return Path(str(resources.files("yaseo").joinpath("rates.json")))


#: Переменная окружения на источник. Ключ — имя источника в `SOURCES`.
RATE_ENV = {
    "search-api": "YASEO_RATE_SEARCH_API",
    "wordstat": "YASEO_RATE_WORDSTAT",
    "движок текста": "YASEO_RATE_ENGINE",
}

#: Прежние имена ключей. Смета — не то место, где опечатка в имени источника
#: может тихо превратить платный вызов в бесплатный. Старое имя принимается и
#: переводится, новое живёт в `SOURCES`.
ALIASES = {"движок": "движок текста"}

#: Реестр источников. Платность — свойство источника, а не вызова: один и тот же
#: вызов на разных проектах тратит одинаково, а два источника с одним именем
#: «запрос» стоят по-разному.
SOURCES: dict[str, dict] = {
    "search-api": {
        "имя": "Yandex Search API",
        "единица": "обращение к выдаче",
        "платный": True,
    },
    "wordstat": {
        "имя": "Yandex Wordstat API",
        "единица": "обращение к частотности",
        "платный": True,
    },
    "движок текста": {
        "имя": "движок текста",
        "единица": "обращение к движку",
        "платный": True,
    },
    "вебмастер": {
        "имя": "Яндекс.Вебмастер",
        "единица": "обращение по OAuth-токену",
        "платный": False,
    },
    "метрика": {
        "имя": "Яндекс.Метрика",
        "единица": "обращение по OAuth-токену",
        "платный": False,
    },
    "нет": {
        "имя": "ничего не тратится",
        "единица": "обращение",
        "платный": False,
    },
}


def pages_for_depth(n: int) -> int:
    """
    Сколько обращений уходит на один снимок выдачи заданной глубины.

    Общее место для трекера и проверки статей: оба считают смету по числу
    «снимков», а платит Яндекс по числу страниц — разойдись они, смета
    назвала бы цену вдвое-втрое ниже настоящей для любого вызова с глубиной
    больше 10.

    Считает не сам: делегирует `yandex_serp.pages_for`, у которого и формула
    страниц, и потолок глубины (`MAX_DEPTH=50`) — источник правды один. Без
    делегирования своя формула для n=100 насчитала бы 10 обращений, а
    `serp()` реально обрежет глубину до 50 и потратит 5 — смета оказалась бы
    вдвое выше настоящей траты. Импорт внутри функции — чтобы модуль сметы
    не тянул сеть и `env` при любом обращении к смете, не связанном с
    глубиной выдачи.
    """
    from .yandex_serp import pages_for as _pages_for
    return _pages_for(n)


def plural(n: int, one: str, few: str, many: str) -> str:
    """Склонение по числу. Публичное: «2 фраз» читается как опечатка и
    роняет доверие ко всей строке."""
    return _plural(n, one, few, many)


def _plural(n: int, one: str, few: str, many: str) -> str:
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def calls_word(n: int) -> str:
    return f"{n} {_plural(n, 'обращение', 'обращения', 'обращений')}"


def _rates_file() -> dict:
    """Настройки ставок. Файла нет — это законное состояние, а не поломка."""
    path = rates_path()
    try:
        data = json.loads(path.read_text(encoding="utf8"))
        return data if isinstance(data, dict) else {}
    except FileNotFoundError:
        return {}
    except (OSError, ValueError) as exc:
        print(f"ставки не прочитаны ({path}: {exc}) — считаю ставку "
              f"незаданной", file=sys.stderr)
        return {}


def rate(source: str) -> tuple[float | None, str]:
    """
    Ставка источника в рублях за обращение и откуда она взята.

    `None` — ставка не задана. Это ответ, а не пропуск: пока её нет, стоимость
    в рублях неизвестна, и смета обязана сказать это словами, а не показать
    ноль или «примерно».
    """
    env_name = RATE_ENV.get(source)
    raw = os.environ.get(env_name) if env_name else None
    откуда = f"переменная {env_name}"
    if raw is None:
        raw = (_rates_file().get("ставки") or {}).get(source)
        откуда = f"{rates_path().name}, ключ «{source}»"
    if raw is None or raw == "":
        return None, "ставка не задана"
    try:
        value = float(str(raw).replace(",", "."))
    except (TypeError, ValueError):
        print(f"ставка источника «{source}» = {raw!r} — не число ({откуда}); "
              f"считаю незаданной", file=sys.stderr)
        return None, "ставка не задана"
    return (value, откуда) if value >= 0 else (None, "ставка не задана")


def _money(value: float) -> str:
    """Рубли по-русски: запятая, разряды пробелом, копейки только если есть."""
    точность = 2 if abs(value - round(value)) >= 0.005 else 0
    text = f"{value:,.{точность}f}".replace(",", " ").replace(".", ",")
    return f"{text} ₽"


def estimate(
    source: str,
    calls: int,
    *,
    project: str | None = None,
    domain: str | None = None,
    из_чего: str | None = None,
    накоплено: str | None = None,
    потолок: int | None = None,
    примечание: str | None = None,
) -> dict:
    """
    Смета одного вызова. Ключи русские: их читает человек.

    `calls` — количество обращений, которое вызов сделает. Ноль — законное
    значение: план, который ничего не зовёт, тоже получает смету.

    `потолок` — сколько обращений разрешено за прогон. Если названо и
    количество его превышает, смета сама говорит «упирается в потолок»: не надо
    предлагать запустить то, что всё равно будет остановлено.
    """
    source = ALIASES.get(source, source)
    src = SOURCES.get(source)
    if src is None:
        # Неизвестный ключ — это не «бесплатно». Молчаливое падение в «нет»
        # превращало бы платный вызов в бесплатный ровно при опечатке в имени
        # источника, и заметить это можно было бы только по счёту.
        print(f"смета: источника «{source}» в SOURCES нет — считаю платным",
              file=sys.stderr)
        src = {"имя": f"неизвестный источник «{source}»",
               "единица": "обращение", "платный": True}
    calls = max(0, int(calls or 0))
    paid = bool(src["платный"]) and calls > 0
    over = bool(потолок) and calls > int(потолок)

    where = " · ".join(p for p in (project, domain) if p) or "проект не выбран"

    lines: list[str] = []
    if not paid:
        # Три разные причины «бесплатно», и путать их нельзя: «источник даром»,
        # «обращений ноль» и «тратить нечем» читаются человеком по-разному.
        if source == "нет":
            lines.append("Ничего не потрачено")
        elif calls == 0:
            lines.append(f"Ничего не потрачено: обращений к «{src['имя']}» ноль")
        else:
            lines.append(f"Ничего не потрачено: {src['имя']} платы за запрос не берёт "
                         f"({calls_word(calls)})")
    else:
        head = f"Потратит: {calls_word(calls)} к «{src['имя']}»"
        lines.append(head + (f" ({из_чего})" if из_чего else ""))

    # Деньги. Ставка не задана — так и говорим: «867 обращений» без рублей
    # человеку не говорит ничего, а выдуманная ставка хуже отсутствующей.
    ставка, откуда = rate(source) if paid else (None, "тратить нечего")
    рублей = None if (ставка is None or not paid) else ставка * calls
    if paid:
        if рублей is None:
            про_деньги = ("Стоимость в рублях: неизвестна — ставка не задана. "
                          f"Задать: {rates_path()}, ключ «{source}», "
                          f"или переменная {RATE_ENV.get(source, '—')}")
        else:
            про_деньги = (f"Стоимость: {_money(рублей)} "
                          f"({calls} × {_money(ставка)}, {откуда})")
        lines.append(про_деньги)
    else:
        про_деньги = "Стоимость: ноль, платить не за что"

    lines.append(f"По проекту: {where}")
    if накоплено:
        lines.append(f"Уже накоплено: {накоплено}")
    # Потолок называется всегда, в том числе когда его нет: «без потолка» —
    # это состояние, о котором человек обязан знать до запуска.
    if потолок:
        lines.append(
            f"Потолок за прогон: {потолок}"
            + (" — прогон в него не укладывается и будет остановлен" if over else "")
        )
    elif paid:
        lines.append("Потолок за прогон: не задан — сверху прогон ничем "
                     "не ограничен")
    if примечание:
        lines.append(примечание)

    return {
        "источник": src["имя"],
        "ключ_источника": source,
        "платный": paid,
        "обращений": calls,
        "из_чего": из_чего,
        "проект": project,
        "домен": domain,
        "накоплено": накоплено,
        "потолок": потолок,
        "за_потолком": over,
        "ставка": ставка,
        "ставка откуда": откуда,
        "рублей": рублей,
        "про деньги": про_деньги,
        "примечание": примечание,
        "строки": lines,
    }


def text(est: dict) -> str:
    """Смета текстом — по строке на ответ."""
    return "\n".join(est["строки"])


def one_line(est: dict) -> str:
    """
    Смета для подтверждения перед тратой. Одной строкой, но количество и источник
    в ней есть всегда: подтверждать вслепую человек не должен.
    """
    if not est["платный"]:
        return f"{est['строки'][0]}. {est['строки'][1]}. Продолжить?"
    из = f" ({est['из_чего']})" if est.get("из_чего") else ""
    where = " · ".join(p for p in (est.get("проект"), est.get("домен")) if p)
    tail = f" по проекту {where}" if where else ""
    # Деньги едут и в короткую форму: подтверждают вслепую именно по ней.
    деньги = (f" Это {_money(est['рублей'])}."
              if est.get("рублей") is not None
              else " Это платно, ставка в рублях не задана — сумма неизвестна.")
    return (f"Будет сделано {calls_word(est['обращений'])} к «{est['источник']}»"
            f"{из}{tail}.{деньги} Продолжить?")


def html(est: dict) -> str:
    """Смета списком. Экранирует сама — снаружи экранировать не надо."""
    cls = "smeta paid" if est["платный"] else "smeta free"
    items = "".join(f"<li>{escape(s)}</li>" for s in est["строки"])
    return f'<ul class="{cls}">{items}</ul>'
